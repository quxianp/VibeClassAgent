//! # vca-plugin-host
//!
//! 插件宿主层：插件的**发现、校验、加载、运行与市场管理**。
//!
//! 设计依据（策划书 4.2 插件机制）。
//!
//! # ⚠️ 当前状态：不可用（v1 未启用）
//!
//! 这套代码能编译、能通过单元测试，但**没有接入任何真实运行路径**，
//! 并且存在两个在启用前必须解决的问题：
//!
//! 1. **超时不可靠**：`runner` 用阻塞的 `read_line()` 读插件 stdout，
//!    插件若不输出换行就永远读不回来，超时判断根本没有机会执行
//!    （评审 R-05）。一个失控插件会卡死整条课后流水线。
//! 2. **权限声明不是沙箱**：`manifest` 里的 `permissions`
//!    （network / filesystem / env）只用于**展示**，进程以当前用户身份
//!    启动，能读任意文件、任意环境变量（评审 R-06）。也就是说
//!    "权限清单"目前是一种安全假象，不能作为信任依据。
//!
//! 因此 CLI 的 `plugin` / `market` 子命令统一回复"尚未实现"，
//! 界面也不提供安装入口。**不要因为模块存在就以为插件可以装**。
//!
//! 启用前必须完成：把 stdout 读取挪到独立线程并实现真超时、
//! 明确权限声明的实际边界（要么实现隔离，要么把措辞降级为"告知"）。
//!
//! # 各模块状态
//!
//! | 模块 | 状态 |
//! |---|---|
//! | [`manifest`] | 可用（清单解析与校验，含测试） |
//! | [`host`] | 可用（插件目录扫描） |
//! | [`runner`] | **不可用**：超时缺陷 + 无沙箱 |
//! | [`market`] | 可用（仅本地目录安装；远程市场未实现） |
//!
//! 运行模式当前**只支持 `process`**（JSON-RPC over stdio）。`cdylib` / `wasm`
//! 在清单校验阶段就会被拒绝：声明了却不按那个方式加载，比直接不支持更糟
//! （评审 R-14）。

#![forbid(unsafe_code)]
#![warn(missing_docs)]

pub mod host;
pub mod manifest;
pub mod market;
pub mod runner;

/// 宿主支持的插件接口大版本。插件的 `api_version` 必须与之匹配。
pub const SUPPORTED_API_VERSION: &str = "1";

/// 插件功能整体是否可用。
///
/// 供 CLI / 界面统一判断，避免每个入口各写一句"暂未实现"而措辞不一。
/// 相关缺陷见模块文档（评审 R-05 / R-06）。
///
/// 改成 `true` 之前请先读模块文档顶部的"启用前必须完成"。
pub const PLUGINS_ENABLED: bool = false;

/// 插件不可用时给用户看的原因（CLI 与界面共用同一句话）。
pub const PLUGINS_UNAVAILABLE_REASON: &str =
    "插件功能尚未启用：运行时的超时与权限隔离还没做完，装上也无法安全使用。当前版本请用内置推送渠道。";
